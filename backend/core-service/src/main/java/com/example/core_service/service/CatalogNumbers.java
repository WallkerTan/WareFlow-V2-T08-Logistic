package com.example.core_service.service;

import lombok.RequiredArgsConstructor;
import org.springframework.boot.ApplicationArguments;
import org.springframework.boot.ApplicationRunner;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;
import java.util.Locale;
import java.util.UUID;

@Service
@RequiredArgsConstructor
public class CatalogNumbers implements ApplicationRunner {
    private final JdbcTemplate db;

    public long next(String scope) {
        return db.queryForObject("""
            insert into catalog_counters(scope, value) values (?, 1)
            on conflict(scope) do update set value=catalog_counters.value+1 returning value
            """, Long.class, scope);
    }

    public String sku(long supplier) {
        return "SK" + supplier + "-" + String.format(Locale.ROOT, "%02d", next("product:" + supplier));
    }

    public String batchCode(UUID companyId) {
        Long company=db.queryForObject("""
                insert into catalog_company_numbers(company_id) values(?)
                on conflict(company_id) do update set company_id=excluded.company_id returning display_id
                """,Long.class,companyId);
        return "LH" + company + "-" + String.format(Locale.ROOT,"%02d",next("batch:"+company));
    }

    @Override @Transactional
    public void run(ApplicationArguments arguments) {
        db.execute("create table if not exists catalog_counters(scope varchar(100) primary key, value bigint not null)");
        db.execute("create table if not exists catalog_company_numbers(company_id uuid primary key, display_id bigint generated by default as identity unique)");
        db.execute("lock table partners, supplier_products in share row exclusive mode");
        for (UUID id : db.queryForList("select id from partners where kind='SUPPLIER' and display_id is null order by id", UUID.class))
            db.update("update partners set display_id=? where id=?",next("supplier"),id);
        db.query("""
            select p.id,p.sku,s.display_id from supplier_products p join partners s on s.id=p.supplier_id
            where p.legacy_sku is null and p.barcode is null order by s.display_id,p.id
            """, (org.springframework.jdbc.core.RowCallbackHandler) r -> {
            UUID id=r.getObject("id",UUID.class);
            String code=sku(r.getLong("display_id"));
            db.update("update supplier_products set legacy_sku=sku,sku=?,barcode=? where id=?",code,"WF"+id.toString().replace("-",""),id);
        });
    }
}
